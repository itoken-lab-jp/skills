/** 箇条書きや強調に置かれやすい絵文字（no-ai-list-formatting・no-ai-emphasis-patterns） */
export const FLASHY_EMOJI = ["✅", "❌", "⭐", "✨", "💯", "⚠️", "❗", "❓", "💥", "🔥", "⚡", "💪", "🚀", "💡", "🤔", "💭", "🧠", "🎯", "📈", "📊", "🏆", "👍", "👎", "😊", "😎", "🎉", "🌟", "📝", "📋", "✏️", "🖊️", "💼", "ℹ️", "🔍", "📌", "🔗"];

/** 「**ポイント**：」のような情報の札（no-ai-emphasis-patterns）。手順書の「**注意**」「**重要**」は警告の定型なので外した */
const INFO_LABELS = ["ポイント", "メモ", "参考", "補足", "確認", "チェック", "推奨", "おすすめ", "良い例", "悪い例", "使用例", "設定例"];

/** 行（front matter・コメント・コードを外したもの）から、Markdown の書き方の型を拾う */
export function formatPatterns(lines) {
    const found = [];
    const emoji = new RegExp(`(${FLASHY_EMOJI.map((e) => e.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|")})`, "u");
    for (const { no, text } of lines) {
        const isList = /^\s*([-*+]|\d+[.)])\s+/.test(text);
        if (isList && /^\s*([-*+]|\d+[.)])\s+\*\*[^*]+\*\*(\s*[:：]|\s+[-—–](?=\s))/.test(text)) {
            found.push({ no, kind: "format", msg: "箇条書きの「**名前**：説明」の形（太字とコロンで項目を立てる形は、AI の文に多い）" });
        }
        if (isList && emoji.test(text)) found.push({ no, kind: "format", msg: "箇条書きの中の絵文字" });
        if (new RegExp(`${emoji.source}\\s*\\*\\*`, "u").test(text)) found.push({ no, kind: "format", msg: "絵文字と太字の組み合わせ" });
        if (new RegExp(`^\\s*\\*\\*(${INFO_LABELS.join("|")})\\*\\*\\s*[:：]?`).test(text)) found.push({ no, kind: "format", msg: "「**ポイント**」のような札を太字で立てている" });
        if (/^#{1,6}\s.*\*\*[^*]+\*\*/.test(text)) found.push({ no, kind: "format", msg: "見出しの中の太字" });
        if (!isList && /(ます|です|る|た|だ)[：:]\s*$/.test(text)) found.push({ no, kind: "format", msg: "文の終わりをコロンで次につなぐ形（「〜します：」）" });
    }
    return found;
}

/** 文ごとに、AI の文に多い語・誇張・決まり文句を拾う */
export function wordPatterns(sentences) {
    const found = [];
    for (const s of sentences) {
        for (const w of AI_WORDS) if (w.re.test(s.text)) found.push({ no: s.no, kind: "aiword", msg: `「${w.label}」は AI の文に多い言い方：${s.text.slice(0, 40)}` });
        for (const h of HYPE) if (s.text.includes(h)) found.push({ no: s.no, kind: "aiword", msg: `誇張「${h}」：${s.text.slice(0, 40)}` });
        for (const [label, re] of TECH_PHRASES) if (re.test(s.text)) found.push({ no: s.no, kind: "aiword", msg: `決まり文句「${label}」：${s.text.slice(0, 40)}` });
    }
    return found;
}
